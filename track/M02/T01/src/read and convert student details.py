# Read and Convert Student Details
# A student registration system receives the student’s name, age and course rating.


# Read and convert the student details
Student_name = input()
Student_age = int(input())
Course_rating = float(input())
# Display the values
print(f"Student: {Student_name}")
print(f"Age: {Student_age}")
print(f"Rating: {Course_rating}")
# Display the data types
print(type(Student_name))
print(type(Student_age))
print(type(Course_rating))